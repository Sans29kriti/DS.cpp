#include<iostream>
#include<cstdlib>
using namespace std;
struct node{
    int data;
    struct node*next;
};
struct node *start=NULL,*ptr;
int val;
void display(){
ptr=start;
    while(ptr!=NULL){
        cout<<ptr->data<<"->";
            ptr = ptr->next;
    }
    cout<< "NULL";
}
void createnode(){
    cout<<"input value to insert";
    cin>>val;
    struct node* newnode=(struct node*)malloc(sizeof(struct node));
    newnode->data=val;
    newnode->next=NULL;
    if(start ==NULL)
        start = newnode;
    else{
        ptr=start;
        while(ptr->next!=NULL)
            ptr=ptr->next;
        ptr->next=newnode;
    }
}
void deletionbeg()
{
    if(start == NULL)
    {
        cout<<"Linked list is empty";
    }
    else
    {
        ptr=start;
        start=start->next;
        free(ptr);
    }
}

int main(){
    int n;
    cout<<"number of nodes;";
    cin>>n;
    for(int i = 0;i<n;i++)
        {
            createnode();
        }
    cout<<"existing linked list is";
    display(); 
    cout<<"\nnow deletion a new value at first \n";
    deletionbeg();
    cout<<"after deletion at first";
    display();
    cout<<"\nfreezing memory.....";
    ptr=start;
        while(ptr!=NULL){
        struct node *nextnode=ptr->next;
        free(ptr);
        ptr= nextnode;
    }
    start=NULL;
    return 0;
};
